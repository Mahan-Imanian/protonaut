//! A headless Xorg server with the dummy video driver.
//!
//! Xvfb is not used: its modes carry no refresh rate, and DXVK 2.7 divides by
//! it while pacing frames (integer division by zero in dxgi.dll, observed with
//! DXVK 2.7.1 on Mesa lavapipe). The dummy driver takes real modelines.

use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::Duration;

use protonaut_core::config::Resolution;
use tokio::io::{AsyncBufReadExt, BufReader};
use tokio::process::{Child, Command};

use crate::RuntimeError;
use crate::supervise::run_tool;

/// Installed under /etc/X11 so a non-root Xorg may load it: a non-root
/// server only accepts config paths relative to its search directories.
pub const SYSTEM_CONFIG_NAME: &str = "protonaut-dummy.conf";
pub const SYSTEM_CONFIG_DIR: &str = "/etc/X11";
const XORG: &str = "/usr/lib/xorg/Xorg";

pub fn mode_name(r: Resolution) -> String {
    format!("{}x{}_60.00", r.width, r.height)
}

/// Modelines from `cvt` for each supported resolution at 60 Hz.
fn modeline(r: Resolution) -> &'static str {
    match (r.width, r.height) {
        (1280, 720) => "74.50 1280 1344 1472 1664 720 723 728 748 -hsync +vsync",
        (1920, 1080) => "173.00 1920 2048 2248 2576 1080 1083 1088 1120 -hsync +vsync",
        _ => "83.50 1280 1352 1480 1680 800 803 809 831 -hsync +vsync",
    }
}

pub fn xorg_config() -> String {
    let mut modelines = String::new();
    let mut modes = Vec::new();
    for r in Resolution::SUPPORTED {
        modelines.push_str(&format!(
            "    Modeline \"{}\" {}\n",
            mode_name(r),
            modeline(r)
        ));
        modes.push(format!("\"{}\"", mode_name(r)));
    }
    format!(
        "# Generated by protonaut. Headless display for Proton tests.\n\
Section \"ServerFlags\"\n    Option \"AutoAddDevices\" \"false\"\n    Option \"AutoEnableDevices\" \"false\"\nEndSection\n\
Section \"Device\"\n    Identifier \"dummy\"\n    Driver \"dummy\"\n    VideoRam 256000\nEndSection\n\
Section \"Monitor\"\n    Identifier \"monitor\"\n    HorizSync 28.0-80.0\n    VertRefresh 48.0-75.0\n{modelines}EndSection\n\
Section \"Screen\"\n    Identifier \"screen\"\n    Device \"dummy\"\n    Monitor \"monitor\"\n    DefaultDepth 24\n    SubSection \"Display\"\n        Depth 24\n        Modes {}\n    EndSubSection\nEndSection\n",
        modes.join(" ")
    )
}

pub struct Display {
    child: Child,
    pub number: u32,
    pub resolution: Resolution,
}

impl Display {
    pub fn name(&self) -> String {
        format!(":{}", self.number)
    }

    /// Starts Xorg and switches it to `resolution`. `work` receives the
    /// generated config when running as root.
    pub async fn start(resolution: Resolution, work: &Path) -> Result<Self, RuntimeError> {
        if !Path::new(XORG).is_file() {
            return Err(RuntimeError::Environment(format!(
                "{XORG} not found; install xserver-xorg-core and xserver-xorg-video-dummy (run `protonaut diagnose`)"
            )));
        }
        let root = nix::unistd::geteuid().is_root();
        let config_arg: PathBuf = if root {
            let p = work.join("xorg-dummy.conf");
            std::fs::write(&p, xorg_config()).map_err(|e| RuntimeError::io(&p, e))?;
            p
        } else {
            let installed = Path::new(SYSTEM_CONFIG_DIR).join(SYSTEM_CONFIG_NAME);
            if !installed.is_file() {
                return Err(RuntimeError::Environment(format!(
                    "{} is missing; a non-root Xorg can only load configs from {SYSTEM_CONFIG_DIR}. Run `sudo protonaut setup`.",
                    installed.display()
                )));
            }
            PathBuf::from(SYSTEM_CONFIG_NAME)
        };
        let mut cmd = Command::new(XORG);
        cmd.arg("-displayfd")
            .arg("1")
            .arg("-noreset")
            .arg("-nolisten")
            .arg("tcp")
            .arg("-novtswitch")
            .arg("-sharevts")
            .arg("+extension")
            .arg("RANDR")
            .arg("-config")
            .arg(&config_arg);
        if root {
            cmd.arg("-logfile").arg(work.join("xorg.log"));
        }
        cmd.stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .process_group(0)
            .kill_on_drop(true);
        let mut child = cmd.spawn().map_err(|e| RuntimeError::Spawn {
            program: XORG.into(),
            message: e.to_string(),
        })?;
        let stdout = child
            .stdout
            .take()
            .ok_or_else(|| RuntimeError::Environment("Xorg stdout unavailable".into()))?;
        let mut line = String::new();
        let read = tokio::time::timeout(
            Duration::from_secs(20),
            BufReader::new(stdout).read_line(&mut line),
        )
        .await;
        let number: u32 = match read {
            Ok(Ok(n)) if n > 0 => line.trim().parse().map_err(|_| {
                RuntimeError::Environment(format!("Xorg reported display {line:?}"))
            })?,
            _ => {
                let _ = child.kill().await;
                return Err(RuntimeError::Environment(
                    "Xorg did not start within 20 s; see xorg.log or ~/.local/share/xorg/".into(),
                ));
            }
        };
        let display = Display {
            child,
            number,
            resolution,
        };
        display.set_mode(resolution).await?;
        Ok(display)
    }

    pub async fn set_mode(&self, r: Resolution) -> Result<(), RuntimeError> {
        let name = self.name();
        run_tool(
            "xrandr",
            &["--display"],
            &[
                name.as_ref(),
                "--output".as_ref(),
                "DUMMY0".as_ref(),
                "--mode".as_ref(),
                mode_name(r).as_ref(),
            ],
            Duration::from_secs(10),
        )
        .await?;
        Ok(())
    }

    /// Reported refresh rate of the current mode, from `xrandr`.
    pub async fn current_mode(&self) -> Result<String, RuntimeError> {
        let name = self.name();
        let out = run_tool(
            "xrandr",
            &["--display"],
            &[name.as_ref()],
            Duration::from_secs(10),
        )
        .await?;
        Ok(out
            .lines()
            .find(|l| l.contains('*'))
            .map(|l| l.split_whitespace().collect::<Vec<_>>().join(" "))
            .unwrap_or_default())
    }

    pub async fn stop(mut self) {
        let _ = self.child.kill().await;
        let _ = self.child.wait().await;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_has_a_modeline_with_refresh_for_every_supported_resolution() {
        let c = xorg_config();
        for r in Resolution::SUPPORTED {
            assert!(c.contains(&format!("Modeline \"{}\"", mode_name(r))), "{r}");
        }
        assert!(c.contains("Driver \"dummy\""));
        assert!(c.contains("VertRefresh"));
    }

    #[test]
    fn deck_mode_is_named_like_xrandr_shows_it() {
        assert_eq!(mode_name(Resolution::DECK), "1280x800_60.00");
    }
}
